// lib/logistics/statusMachine.js

import { SHIPMENT_STATUSES as S } from "../constants/shipmentStatus";

export const ALLOWED_TRANSITIONS = {
  [S.LABEL_CREATED]: [S.PICKED_UP, S.EXCEPTION],
  [S.PICKED_UP]: [S.AT_ORIGIN_HUB, S.EXCEPTION],
  [S.AT_ORIGIN_HUB]: [S.EXPORT_CUSTOMS_PENDING, S.INTERNATIONAL_TRANSIT, S.EXCEPTION],
  [S.EXPORT_CUSTOMS_PENDING]: [S.EXPORT_CUSTOMS_CLEARED, S.EXCEPTION],
  [S.EXPORT_CUSTOMS_CLEARED]: [S.INTERNATIONAL_TRANSIT, S.EXCEPTION],
  [S.INTERNATIONAL_TRANSIT]: [S.ARRIVED_DESTINATION_COUNTRY, S.EXCEPTION],
  [S.ARRIVED_DESTINATION_COUNTRY]: [S.IMPORT_CUSTOMS_PENDING, S.EXCEPTION],
  [S.IMPORT_CUSTOMS_PENDING]: [S.IMPORT_CUSTOMS_CLEARED, S.EXCEPTION],
  [S.IMPORT_CUSTOMS_CLEARED]: [S.AT_DESTINATION_HUB, S.EXCEPTION],
  [S.AT_DESTINATION_HUB]: [S.OUT_FOR_DELIVERY, S.EXCEPTION],
  [S.OUT_FOR_DELIVERY]: [S.DELIVERED, S.DELIVERY_FAILED, S.EXCEPTION],
  [S.DELIVERY_FAILED]: [S.OUT_FOR_DELIVERY, S.RETURN_TO_SENDER],
  [S.RETURN_TO_SENDER]: [],
  // An exception can be resolved back into the main flow by an admin.
  [S.EXCEPTION]: [
    S.PICKED_UP,
    S.AT_ORIGIN_HUB,
    S.EXPORT_CUSTOMS_PENDING,
    S.INTERNATIONAL_TRANSIT,
    S.IMPORT_CUSTOMS_PENDING,
    S.AT_DESTINATION_HUB,
    S.OUT_FOR_DELIVERY,
    S.RETURN_TO_SENDER,
  ],
  [S.DELIVERED]: [],
};

export function canTransition(from, to) {
  return (ALLOWED_TRANSITIONS[from] ?? []).includes(to);
}

export function nextStatuses(from) {
  return ALLOWED_TRANSITIONS[from] ?? [];
}
